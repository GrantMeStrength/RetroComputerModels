def keys(variant):
    layout = LAYOUTS[variant]
    result = []
    for row, bounds in enumerate(layout["key_bounds"]):
        for col, (x0, y0, x1, y1) in enumerate(bounds):
            x, y = (x0+x1)/2, (y0+y1)/2
            width, height = x1-x0, y1-y0
            result.append({
                "row": row, "column": col, "legend": layout["legends"][row][col],
                "pixel_center": [x, y], "pixel_size": [width, height],
                "pixel_bounds": [x0, y0, x1, y1],
                "center_mm": [(x/IMAGE_WIDTH-0.5)*PLATE_WIDTH,
                              72-PLATE_START-y/IMAGE_HEIGHT*PLATE_DEPTH],
                "size_mm": [width/IMAGE_WIDTH*PLATE_WIDTH, height/IMAGE_HEIGHT*PLATE_DEPTH],
            })
    return result
